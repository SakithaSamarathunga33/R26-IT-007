"""Train + evaluate the reliability-aware logistic fusion model; export it as a JSON artifact.

Usage (Python 3.11 + backend/multi_modal_risk/api/requirements.txt):
    python training/train_reliability_fusion.py            # from backend/multi_modal_risk

The synthetic fusion dataset has clean module scores only, so evidence degradation is SIMULATED
inside each training fold: modules go missing and scores get noise sized by a reliability level.
All simulation settings below were fixed before any evaluation was run; nothing is tuned toward a target.
The label (final_dyslexia_risk_label) was generated by the dataset's weighted rule on CLEAN scores, so the
model learns to recover the clean-evidence decision from degraded, partial evidence. It is not clinical accuracy.
"""
import hashlib, json, sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, brier_score_loss, confusion_matrix, recall_score, roc_auc_score
from sklearn.model_selection import GroupKFold
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'api'))
from app.services.reliability_features import FEATURE_ORDER, MODULES, build_features  # noqa: E402
from app.services.fusion_service import effective_weights, load_rule_config  # noqa: E402

DATASET = ROOT / 'datasets' / 'fusion_training_dataset_synthetic.csv'
OUT_MODEL = ROOT / 'ml_models' / 'fusion_reliability_lr_v1.json'
OUT_REPORT = Path(__file__).with_name('REPORT.md')

SEED = 42
RELIABILITY_LEVELS = ['high', 'medium', 'low']
RELIABILITY_P = [0.5, 0.35, 0.15]                            # how often each level occurs
NOISE_SD = {'high': 0.03, 'medium': 0.08, 'low': 0.18}      # score noise per reliability level
P_MISSING = 0.15                                            # chance a module is unavailable
AUGMENT_COPIES = 8                                          # degraded copies per training row
DECISION_THRESHOLD = 0.5                                    # probability cut-off for the binary label
SCORE_COLS = {'speech': 'speech_score', 'handwriting': 'handwriting_score', 'behavior': 'behavior_score'}


def degrade(clean, rng, p_missing=P_MISSING, rel_p=RELIABILITY_P, force_missing=False):
    """clean: (n, 3) module scores. Returns per-row (probs dict, reliabilities dict); always >= 2 modules usable."""
    rows = []
    for scores in clean:
        rels = {m: rng.choice(RELIABILITY_LEVELS, p=rel_p) for m in MODULES}
        missing = {m: rng.random() < p_missing for m in MODULES}
        if force_missing:
            missing = {m: False for m in MODULES}
            missing[rng.choice(MODULES)] = True
        while sum(not v for v in missing.values()) < 2:
            missing[rng.choice([m for m in MODULES if missing[m]])] = False
        probs = {
            m: None if missing[m] else float(np.clip(s + rng.normal(0, NOISE_SD[rels[m]]), 0, 1))
            for m, s in zip(MODULES, scores)
        }
        rows.append((probs, rels))
    return rows


def matrix(rows):
    return np.array([build_features(p, r) for p, r in rows])


def rule_v1(rows):
    """The original fixed rule: missing module scored as 0."""
    w = {'speech': 0.40, 'handwriting': 0.35, 'behavior': 0.25}
    return np.array([sum(w[m] * (p[m] or 0.0) for m in MODULES) for p, _ in rows])


def rule_v2(rows, config):
    """The current service rule: reliability-weighted, renormalised over usable modules."""
    out = []
    for probs, rels in rows:
        statuses = {m: {'usable': probs[m] is not None, 'score': probs[m], 'reliability': rels[m]} for m in MODULES}
        w = effective_weights(statuses, config)
        out.append(sum(w[m] * probs[m] for m in MODULES if probs[m] is not None))
    return np.array(out)


def metrics(y, score, threshold):
    pred = (score >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return dict(accuracy=accuracy_score(y, pred), sensitivity=recall_score(y, pred), specificity=recall_score(1 - y, 1 - pred),
                auc=roc_auc_score(y, score), tp=tp, fn=fn, fp=fp, tn=tn)


def fit(X, y):
    scaler = StandardScaler().fit(X)
    model = LogisticRegression(max_iter=2000, random_state=SEED).fit(scaler.transform(X), y)
    return scaler, model


def main():
    df = pd.read_csv(DATASET)
    clean = df[[SCORE_COLS[m] for m in MODULES]].to_numpy()
    y = df['final_dyslexia_risk_label'].astype(int).to_numpy()
    groups = df['child_id'].to_numpy()
    config = load_rule_config()

    scenarios = {
        'clean (all modules, high reliability)': dict(p_missing=0.0, rel_p=[1.0, 0.0, 0.0]),
        'realistic mix (15% missing, mixed reliability)': dict(),
        'one module missing (medium reliability)': dict(rel_p=[0.0, 1.0, 0.0], force_missing=True),
        'low reliability everywhere': dict(p_missing=0.0, rel_p=[0.0, 0.0, 1.0]),
    }
    results = []
    for fold, (tr, te) in enumerate(GroupKFold(n_splits=5).split(clean, y, groups)):
        assert not set(groups[tr]) & set(groups[te])
        rng = np.random.default_rng(SEED + fold)
        train_rows = [r for _ in range(AUGMENT_COPIES) for r in degrade(clean[tr], rng)]
        scaler, model = fit(matrix(train_rows), np.tile(y[tr], AUGMENT_COPIES))
        for name, kw in scenarios.items():
            test_rows = degrade(clean[te], np.random.default_rng(1000 + fold), **kw)
            prob = model.predict_proba(scaler.transform(matrix(test_rows)))[:, 1]
            for method, score, thr in [
                ('fixed rule v1 (missing = 0)', rule_v1(test_rows), 0.35),
                ('reliability-weighted rule v2', rule_v2(test_rows, config), 0.35),
                ('reliability-aware logistic fusion', prob, DECISION_THRESHOLD),
            ]:
                m = metrics(y[te], score, thr)
                if method.startswith('reliability-aware'):
                    m['brier'] = brier_score_loss(y[te], prob)
                results.append(dict(scenario=name, method=method, fold=fold, **m))

    res = pd.DataFrame(results)
    summary = res.groupby(['scenario', 'method'], sort=False).agg(
        accuracy=('accuracy', 'mean'), sensitivity=('sensitivity', 'mean'), specificity=('specificity', 'mean'),
        auc=('auc', 'mean'), brier=('brier', 'mean'), tp=('tp', 'sum'), fn=('fn', 'sum'), fp=('fp', 'sum'), tn=('tn', 'sum'))
    print(summary.round(3).to_string())

    # final model on all children, same augmentation
    rng = np.random.default_rng(SEED)
    all_rows = [r for _ in range(AUGMENT_COPIES) for r in degrade(clean, rng)]
    scaler, model = fit(matrix(all_rows), np.tile(y, AUGMENT_COPIES))
    artifact = {
        'model_name': 'reliability_aware_logistic_fusion',
        'model_version': 'reliability_aware_lr_v1',
        'feature_order': FEATURE_ORDER,
        'scaler_mean': scaler.mean_.round(8).tolist(),
        'scaler_scale': scaler.scale_.round(8).tolist(),
        'coefficients': model.coef_[0].round(8).tolist(),
        'intercept': round(float(model.intercept_[0]), 8),
        'decision_threshold': DECISION_THRESHOLD,
        'training': {
            'dataset': DATASET.name,
            'dataset_sha256': hashlib.sha256(DATASET.read_bytes()).hexdigest(),
            'rows': int(len(df)), 'children': int(len(set(groups))),
            'augmentation': dict(copies=AUGMENT_COPIES, p_missing=P_MISSING, reliability_p=dict(zip(RELIABILITY_LEVELS, RELIABILITY_P)), noise_sd=NOISE_SD),
            'seed': SEED, 'sklearn_version': sklearn.__version__, 'trained_on': date.today().isoformat(),
            'evaluation': 'child-disjoint 5-fold GroupKFold; see training/REPORT.md',
        },
        'note': 'Trained on SYNTHETIC data whose label is a rule on clean module scores. Screening support only, not a diagnosis; not clinically validated.',
    }
    OUT_MODEL.write_text(json.dumps(artifact, indent=2), encoding='utf-8')

    lines = ['# Reliability-aware fusion: training report', '',
             f'Dataset: `{DATASET.name}` ({len(df)} sessions, {len(set(groups))} children). '
             'Evaluation: 5-fold GroupKFold by child (no child in both train and test). '
             f'Simulation settings fixed in advance: P(missing)={P_MISSING}, reliability mix {dict(zip(RELIABILITY_LEVELS, RELIABILITY_P))}, noise SD {NOISE_SD}.', '',
             'The label was generated by the dataset\'s weighted rule on clean scores, so these numbers measure how well each '
             'method recovers the clean-evidence decision from degraded or partial evidence. They are not clinical accuracy.', '',
             '| Scenario | Method | Accuracy | Sensitivity | Specificity | AUC | Brier | TP | FN | FP | TN |',
             '|---|---|---|---|---|---|---|---|---|---|---|']
    for (scen, method), r in summary.iterrows():
        brier = '' if pd.isna(r.brier) else f'{r.brier:.3f}'
        lines.append(f'| {scen} | {method} | {r.accuracy:.3f} | {r.sensitivity:.3f} | {r.specificity:.3f} | {r.auc:.3f} | {brier} | {r.tp} | {r.fn} | {r.fp} | {r.tn} |')
    OUT_REPORT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'\nWrote {OUT_MODEL} and {OUT_REPORT}')


if __name__ == '__main__':
    main()
